// Training progress glue: activity days (streak), counters, achievements and today's challenges.
// Counters live on the profile object (Python preserves unknown keys), so they travel with export/import.
import { py } from "../bridge/py";
import { db, store } from "../bridge/storage";
import type { Achievement, Challenge, Profile } from "../bridge/types";
import { ensureProfile } from "../dialogs/LevelCard";
import { today } from "./chess";
import { toast } from "../components/Toast";

const addDays = (d: string, n: number) => { const x = new Date(d + "T00:00:00Z"); x.setUTCDate(x.getUTCDate() + n); return x.toISOString().slice(0, 10); };

export function streakOf(days: string[], t = today()): number {
  const set = new Set(days);
  let d = set.has(t) ? t : addDays(t, -1);
  let n = 0;
  while (set.has(d)) { n++; d = addDays(d, -1); }
  return n;
}

export type Counter = "puzzles_solved" | "lessons_done" | "endgames_done";

/** Record that the user trained today, optionally bumping a counter. Returns the updated profile. */
export async function markActivity(counter?: Counter): Promise<Profile> {
  const p = await ensureProfile();
  const days = new Set<string>((p.activity as string[] | undefined) ?? []);
  days.add(today());
  const np: Profile = { ...p, activity: [...days].sort().slice(-400) };
  if (counter) np[counter] = ((p[counter] as number | undefined) ?? 0) + 1;
  await store.setProfile(np);
  await refreshAchievements(np);
  return np;
}

export async function achievementStats(profile?: Profile | null) {
  const p = profile ?? (await store.getProfile());
  const games = await db.games.toArray();
  const analyses = await db.analysis.toArray();
  const rated = games.filter((g) => g.mode === "bot" && g.result !== "*");
  const wins = rated.filter((g) => (g.result === "1-0") === (g.playerColor === "w") && g.result !== "1/2-1/2").length;
  let clean = 0, bestAcc = 0;
  for (const a of analyses) {
    const pc = a.game.player_color;
    const mine = a.classification.moves.filter((m) => m.is_player);
    if (a.game.mode === "bot" && mine.length && !mine.some((m) => m.class === "blunder")) clean++;
    if (a.game.mode === "bot") bestAcc = Math.max(bestAcc, a.classification.accuracy[pc] ?? 0);
  }
  const challenges = await db.challenges.toArray();
  return {
    games: rated.length, wins, clean_games: clean, best_accuracy: bestAcc,
    puzzles_solved: (p?.puzzles_solved as number | undefined) ?? 0,
    streak: streakOf(((p?.activity as string[] | undefined) ?? [])),
    lessons_done: (await db.lessonProgress.toArray()).filter((r) => r.done && !String(r.id).includes(":")).length,
    challenges_done: challenges.filter((c) => c.done).length,
  };
}

export async function refreshAchievements(profile?: Profile | null): Promise<Achievement[]> {
  const p = profile ?? (await store.getProfile());
  if (!p) return [];
  const fresh = await py.check_achievements(p, await achievementStats(p), await db.achievements.toArray()).catch(() => [] as Achievement[]);
  if (fresh.length) {
    await db.achievements.bulkPut(fresh.map((a) => ({ ...a, date: today() })));
    toast(`Achievement: ${String(fresh[0].title ?? fresh[0].id)}${fresh.length > 1 ? ` (+${fresh.length - 1})` : ""}`);
  }
  return fresh;
}

/** Today's challenges; generated by Python once per day. */
export async function todaysChallenges(): Promise<Challenge[]> {
  const t = today();
  const all = await db.challenges.toArray();
  const mine = all.filter((c) => String(c.date ?? c.id).startsWith(t));
  if (mine.length) return mine;
  const p = await ensureProfile();
  const gen = await py.generate_challenges(await store.getWeakness(), p, t).catch(() => [] as Challenge[]);
  if (gen.length) await db.challenges.bulkPut(gen);
  return gen;
}

